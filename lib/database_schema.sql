CREATE TABLE courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  title TEXT NOT NULL,
  credits INT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('planned', 'active', 'done')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

